-- check: 141 components for the 2025 bylaw (72 lecture, 16 tutorial, 53 lab)
DO $$
DECLARE
  total_count integer;
  lecture_count integer;
  tutorial_count integer;
  lab_count integer;
BEGIN
  SELECT
    count(*),
    count(*) FILTER (WHERE cc.component_type = 'lecture'),
    count(*) FILTER (WHERE cc.component_type = 'tutorial'),
    count(*) FILTER (WHERE cc.component_type = 'lab')
  INTO total_count, lecture_count, tutorial_count, lab_count
  FROM course_component cc
  JOIN course c ON c.id = cc.course_id
  JOIN bylaw b ON b.id = c.bylaw_id
  WHERE b.code = 'bylaw_2025';

  IF total_count <> 141 OR lecture_count <> 72 OR tutorial_count <> 16 OR lab_count <> 53 THEN
    RAISE EXCEPTION 'Expected 141 bylaw_2025 course components (72 lecture, 16 tutorial, 53 lab), found % (% lecture, % tutorial, % lab)',
      total_count, lecture_count, tutorial_count, lab_count;
  END IF;
END $$;
